import type { Language } from './LanguageContext'

/**
 * Teksty interfejsu pisane po polsku wprost w komponentach: `tr('Tekst')` zwraca tłumaczenie
 * dla bieżącego języka (albo polski oryginał, gdy tłumaczenia nie ma). `{0}`, `{1}`… zastępują
 * kolejne argumenty. Ten sam słownik tłumaczy etykiety i błędy przychodzące z procesu głównego.
 */
let current: Language = 'pl'

export function setTrLanguage(language: Language) {
  current = language
}

export function currentLanguage(): Language {
  return current
}

export function tr(pl: string, ...args: Array<string | number>): string {
  let text = current === 'en' ? en[pl] ?? pl : pl
  args.forEach((arg, i) => { text = text.split(`{${i}}`).join(String(arg)) })
  return text
}

